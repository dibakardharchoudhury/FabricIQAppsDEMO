import assert from 'node:assert/strict'
import test from 'node:test'

import {
  mapPublicEnvForFramework,
  parseEnvContent,
  serializeEnvContent,
} from '@microsoft/rayfin-tools-common/_internal/config'
import {
  parseEnv,
  validateEnv,
  validateGeneratedEnv,
} from './validate-env.mjs'

const valid = `
FABRIC_WORKSPACE_NAME=Demo Workspace
RAYFIN_PUBLIC_WORKSPACE_ID=a79a4b7e-e508-4fa4-8b6f-15deadca0f34
RAYFIN_PUBLIC_AAD_CLIENT_ID=22dedc54-8b7e-442c-929d-497c4df086e6
RAYFIN_PUBLIC_TENANT_ID=ad340c84-1886-4202-a483-2da2cb9168eb
RAYFIN_PUBLIC_ENABLE_ENERGY_MAP=false
`

test('accepts the complete deployment contract', () => {
  assert.deepEqual(validateEnv(valid), [])
})

test('rejects the empty SPA client ID that produces a broken deployed bundle', () => {
  const problems = validateEnv(valid.replace(
    'RAYFIN_PUBLIC_AAD_CLIENT_ID=22dedc54-8b7e-442c-929d-497c4df086e6',
    'RAYFIN_PUBLIC_AAD_CLIENT_ID=',
  ))

  assert.deepEqual(problems, ['RAYFIN_PUBLIC_AAD_CLIENT_ID is missing or empty'])
})

test('rejects template placeholders and malformed identifiers', () => {
  const problems = validateEnv(valid
    .replace('Demo Workspace', '<your Fabric workspace display name>')
    .replace('ad340c84-1886-4202-a483-2da2cb9168eb', 'not-a-guid'))

  assert.deepEqual(problems, [
    'FABRIC_WORKSPACE_NAME is missing or empty',
    'RAYFIN_PUBLIC_TENANT_ID must be a GUID',
  ])
})

test('parses values containing equals signs without truncating them', () => {
  assert.equal(parseEnv('SETTING=https://example.test?a=b').SETTING, 'https://example.test?a=b')
})

test('requires an explicit energy map feature flag', () => {
  const problems = validateEnv(valid.replace('RAYFIN_PUBLIC_ENABLE_ENERGY_MAP=false\n', ''))

  assert.deepEqual(problems, ['RAYFIN_PUBLIC_ENABLE_ENERGY_MAP is missing or empty'])
})

test('rejects malformed feature flags', () => {
  const problems = validateEnv(valid.replace(
    'RAYFIN_PUBLIC_ENABLE_ENERGY_MAP=false',
    'RAYFIN_PUBLIC_ENABLE_ENERGY_MAP=yes',
  ))

  assert.deepEqual(problems, ['RAYFIN_PUBLIC_ENABLE_ENERGY_MAP must be true or false'])
})

test('accepts the Vite projection generated by the installed Rayfin mapper', () => {
  const source = valid.replace(
    'RAYFIN_PUBLIC_ENABLE_ENERGY_MAP=false',
    'RAYFIN_PUBLIC_ENABLE_ENERGY_MAP=true',
  )
  const mapped = mapPublicEnvForFramework(parseEnvContent(source), 'vite')
  const generated = serializeEnvContent(mapped)

  assert.equal(mapped.get('VITE_RAYFIN_ENABLE_ENERGY_MAP'), 'true')
  assert.deepEqual(validateGeneratedEnv(source, generated), [])
})

test('rejects a generated Vite environment without the energy map projection', () => {
  assert.deepEqual(validateGeneratedEnv(valid, ''), [
    'VITE_RAYFIN_ENABLE_ENERGY_MAP is missing from generated .env.local',
  ])
})
